// Pin the CSS to the same wheel as the Python renderer. No hand-authored color or
// typography approximations: preserve upstream declarations, scope selectors,
// and scale rem units to the user's document font setting.
import fs from "node:fs";
import path from "node:path";
import crypto from "node:crypto";
import postcss from "postcss";
const version = "0.0.66";
// Both the stylesheets and the license are read from the same pinned wheel, so the
// vendored copy can never drift from the CSS it describes.
const source = ".venv/Lib/site-packages/zensical/templates/assets/stylesheets";
const license = `.venv/Lib/site-packages/zensical-${version}.dist-info/licenses/LICENSE.md`;
const manifest = { version, files: [] };
let output = `/* Generated by scripts/sync-zensical-styles.mjs from Zensical ${version} (MIT).\n * See public/vendor/zensical/LICENSE.md. Do not edit by hand. */\n`;
for (const variant of ["modern", "classic"]) {
  const scope = `.znote-render-scope[data-zn-variant="${variant}"]`;
  for (const kind of ["main", "palette"]) {
    const name = fs
      .readdirSync(path.join(source, variant))
      .find((n) => n.startsWith(kind + ".") && n.endsWith(".css"));
    const raw = fs.readFileSync(path.join(source, variant, name), "utf8");
    const dest = `public/vendor/zensical/${variant}`;
    fs.mkdirSync(dest, { recursive: true });
    fs.writeFileSync(`${dest}/${name}`, raw);
    manifest.files.push({
      variant,
      file: name,
      sha256: crypto.createHash("sha256").update(raw).digest("hex"),
    });
    const root = postcss.parse(raw);
    root.walkRules((rule) => {
      if (
        rule.parent.type === "atrule" &&
        rule.parent.name.includes("keyframes")
      ) {
        rule.remove();
        return;
      }
      const selectors = [];
      for (let selector of rule.selectors) {
        if (selector.includes(":root"))
          selector = selector.replaceAll(":root", scope);
        else if (selector.startsWith("[data-md-color-"))
          selector = scope + selector;
        else if (
          selector.includes(".md-typeset") ||
          selector.includes(".md-icon") ||
          selector.includes(".md-code__") ||
          /\.(?:highlight|highlighttable|linenodiv)(?=[\s.:#>+~[]|$)/.test(
            selector,
          )
        ) {
          selector = selector.replace(/^html\s+/, "");
          if (/^\.(?:no-js|js) /.test(selector))
            selector = selector.replace(/^\.(no-js|js) /, `${scope}.$1 `);
          else if (selector.startsWith("[dir=")) selector = scope + selector;
          else selector = scope + " " + selector;
        } else continue;
        selectors.push(selector);
      }
      if (!selectors.length) {
        rule.remove();
        return;
      }
      rule.selectors = selectors;
      rule.walkDecls((decl) => {
        // Do not rewrite SVG data URLs. rem occurs only in numeric CSS lengths.
        decl.value = decl.value.replace(
          /(-?(?:\d*\.)?\d+)rem\b/g,
          (_, n) => `calc(var(--znote-rem) * ${n})`,
        );
      });
    });
    root.walkAtRules((rule) => {
      if (
        rule.name === "charset" ||
        rule.name.includes("keyframes") ||
        (rule.nodes && !rule.nodes.length)
      )
        rule.remove();
    });
    output += root.toString() + "\n";
  }
}
fs.writeFileSync("src/zensical.generated.css", output);
fs.copyFileSync(license, "public/vendor/zensical/LICENSE.md");
fs.writeFileSync(
  "public/vendor/zensical/manifest.json",
  JSON.stringify(manifest, null, 2) + "\n",
);
console.log(
  `Vendored Zensical ${version}: ${manifest.files.length} upstream stylesheets; scoped CSS ${output.length} bytes.`,
);
